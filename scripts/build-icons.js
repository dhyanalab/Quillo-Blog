// Copies the brand logos the blog uses from Simple Icons (CC0) into src/web/brand-paths.js,
// so the site has no runtime dependency on the icon package. Run after adding a network:
//   npm run build:icons
import fs from "node:fs";
import path from "node:path";
import * as si from "simple-icons";
import { ROOT } from "../src/config.js";

const SLUGS = ["youtube", "instagram", "facebook", "x", "github", "whatsapp", "telegram", "discord", "threads", "reddit", "medium", "hackster", "instructables", "thingiverse", "printables", "pinterest", "tiktok", "bluesky", "googlesearchconsole", "plausibleanalytics", "umami"];
// LinkedIn left Simple Icons in 2024; this is the last published path.
const EXTRA = {
  linkedin: {
    hex: "0A66C2",
    path: "M20.447 20.452h-3.554v-5.569c0-1.328-.027-3.037-1.852-3.037-1.853 0-2.136 1.445-2.136 2.939v5.667H9.351V9h3.414v1.561h.046c.477-.9 1.637-1.85 3.37-1.85 3.601 0 4.267 2.37 4.267 5.455v6.286zM5.337 7.433a2.062 2.062 0 0 1-2.063-2.065 2.064 2.064 0 1 1 2.063 2.065zm1.782 13.019H3.555V9h3.564v11.452zM22.225 0H1.771C.792 0 0 .774 0 1.729v20.542C0 23.227.792 24 1.771 24h20.451C23.2 24 24 23.227 24 22.271V1.729C24 .774 23.2 0 22.222 0h.003z",
  },
};

// The paths go straight into every public page's SVG markup, so a path may hold only what SVG path data is made of
// (command letters, numbers, signs, dots, commas and spaces), and a colour only six hex digits. Anything else stops the build.
// test/fix2-services.test.js applies the same rule to the committed file.
const PATH_OK = /^[MmLlHhVvCcSsQqTtAaZz0-9eE+\-.,\s]+$/;
const HEX_OK = /^[0-9A-Fa-f]{6}$/;

const out = {};
for (const slug of SLUGS) {
  const icon = si[`si${slug[0].toUpperCase()}${slug.slice(1)}`];
  if (!icon) throw new Error(`Simple Icons has no "${slug}"`);
  out[slug] = { hex: icon.hex, path: icon.path };
}
Object.assign(out, EXTRA);
for (const [slug, icon] of Object.entries(out)) {
  if (!PATH_OK.test(icon.path)) throw new Error(`The path for "${slug}" has characters that don't belong in SVG path data. Not written.`);
  if (!HEX_OK.test(icon.hex)) throw new Error(`The colour for "${slug}" is not six hex digits. Not written.`);
}
const body = `// Generated by scripts/build-icons.js from Simple Icons (CC0). Don't edit by hand.\nexport const BRAND_PATHS = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync(path.join(ROOT, "src", "web", "brand-paths.js"), body);
console.log(`Wrote ${Object.keys(out).length} brand logos to src/web/brand-paths.js`);
